#!/usr/bin/env python
"""Task 3: two cups (hot, cold) before a flat matte background, one test frame with the Cellplus draft.

Everything editable is in params.yaml (distances, cup size / material / temperature, background and
table temperature and material, air temperature, display window). This script turns it into
    out/scene_two_cups.yaml      the scene the repo's loader reads (prescribed temperatures)
    out/weather_constant.csv     a constant-air weather file: ONE WeatherSeries feeds the atmosphere
                                 and the enclosure (CLAUDE.md rule 6)
and renders through the same path as task 1 (common.py: Kit G-buffer + host run_frame).

    /home/jumasaet/isaac_sim/python.sh bench/camera_preview/two_cups/render_two_cups.py [params.yaml]

Writes to render.out_dir: frame.png (fixed window), frame_labelled.png (with per-object apparent T),
frame_rgb.png, frame_dn16.npy, frame_apparent_t_k.npy, report.json.
"""
from __future__ import annotations

import json
import math
import pathlib
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import common as cm  # noqa: E402

PARAMS = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "params.yaml"
P = yaml.safe_load(PARAMS.read_text(encoding="utf-8"))
OUT = cm.REPO / P["render"]["out_dir"]
OUT.mkdir(parents=True, exist_ok=True)

import numpy as np  # noqa: E402


def objects_from_params(p: dict) -> tuple[list[dict], dict]:
    """Stage table (nave_stage.author_stage format) + {name: (material, T C)}."""
    objs, thermal = [], {}
    bg = p["background"]
    thick = 0.02
    objs.append(dict(name="Background", kind="box", centre=(-bg["distance_m"] - thick / 2, 0.0, bg["height_m"] / 2 - 0.05),
                     size=(thick, bg["width_m"], bg["height_m"]), rgb=(0.80, 0.80, 0.78)))
    thermal["Background"] = (bg["material"], bg["t_c"])
    if p["table"]["enabled"]:
        x0, x1 = 0.3, -bg["distance_m"]
        objs.append(dict(name="Table", kind="box", centre=((x0 + x1) / 2, 0.0, -0.01), size=(x0 - x1, bg["width_m"], 0.02),
                         rgb=(0.55, 0.42, 0.28)))
        thermal["Table"] = (p["table"]["material"], p["table"]["t_c"])
    colours = [(0.85, 0.30, 0.20), (0.25, 0.45, 0.85)]
    for i, c in enumerate(p["cups"]):
        if c["distance_m"] - c["radius_m"] <= 0.0 or c["distance_m"] + c["radius_m"] >= bg["distance_m"]:
            raise SystemExit(f"{c['name']}: the cup must stand between the camera and the background")
        objs.append(dict(name=c["name"], kind="cyl", centre=(-c["distance_m"], c["lateral_m"], c["height_m"] / 2),
                         size=(c["radius_m"], c["height_m"], "Z"), rgb=colours[i % 2]))
        thermal[c["name"]] = (c["material"], c["t_c"])
    return objs, thermal


def camera_pose(p: dict) -> tuple[np.ndarray, np.ndarray]:
    pos = np.array([0.0, 0.0, p["camera"]["height_m"]])
    if p["camera"].get("aim"):
        aim = np.asarray(p["camera"]["aim"], float)
    else:
        cs = p["cups"]
        aim = np.array([-np.mean([c["distance_m"] for c in cs]), np.mean([c["lateral_m"] for c in cs]),
                        np.mean([c["height_m"] for c in cs]) / 2])
    look = aim - pos
    return pos, look / np.linalg.norm(look)


def write_weather(p: dict) -> pathlib.Path:
    t = p["room"]["t_air_c"] + 273.15
    rows = [f"2024-06-21T{h:02d}:00:00Z,{t:.2f},{p['room']['rh_fraction']},0.1,1.0,0.0,0.0,23000.0,0.0" for h in range(24)]
    rows += [f"2024-06-22T{h:02d}:00:00Z,{t:.2f},{p['room']['rh_fraction']},0.1,1.0,0.0,0.0,23000.0,0.0" for h in range(24)]
    path = OUT / "weather_constant.csv"
    path.write_text("# irsim weather v1\n# SYNTHETIC closed room: constant air temperature, fully covered, no sun "
                    "(GENERATED by render_two_cups.py from params.yaml)\n"
                    "time_utc,t_air_k,rh_fraction,wind_speed_m_s,cloud_fraction,dni_w_m2,dhi_w_m2,visibility_m,precip_mm_h\n"
                    + "\n".join(rows) + "\n")
    return path


def write_scene(thermal: dict, weather: pathlib.Path) -> pathlib.Path:
    rows = "\n".join(f"    - {{name: {cm.ns.target_name(n)}, solver: prescribed, schedule_s: [0.0, 86400.0], "
                     f"schedule_k: [{t + 273.15:.2f}, {t + 273.15:.2f}]}}  # {t:g} C, {m}" for n, (m, t) in thermal.items())
    path = OUT / "scene_two_cups.yaml"
    path.write_text(f"""# Two-cup template scene. GENERATED by render_two_cups.py from {PARAMS.name}; edit that, not this.
schema_version: 17
scene:
  name: two_cups
  description: "Hot and cold cup before a flat matte background, prescribed temperatures, isothermal room"
  weather_file: {weather}
  atmosphere_preset: us_standard_clear
  environment_preset: {cm.ENV_ISOTHERMAL}
  site: {{latitude_deg: 37.5, longitude_deg: 127.0, altitude_m: 50.0}}
  start_utc: "2024-06-21T02:00:00Z"

  targets:
{rows}
""")
    return path


objs, thermal = objects_from_params(P)
pos, look = camera_pose(P)
scene_yaml = write_scene(thermal, write_weather(P))
ctx = cm.boot(sensor_yaml=cm.REPO / P["sensor_yaml"], scene_yaml=scene_yaml, objects=objs,
              materials={n: m for n, (m, _t) in thermal.items()}, first_pose=(pos, look))

from PIL import Image, ImageDraw  # noqa: E402

from irsim_isaac.pipeline.material_ids import labels_from_payload, labels_to_paths  # noqa: E402

clock = cm.Clock(ctx)
for _ in range(int(P["render"]["warmup_frames"])):
    clock.frame(cm.render_sync(ctx, pos, look))
payload = cm.render_sync(ctx, pos, look)
out, rgb, ids_ss = clock.frame(payload)
lo, hi = P["render"]["window_c"]
gray = cm.window_gray(out.apparent_t, lo, hi)
Image.fromarray(gray).save(OUT / "frame.png")
Image.fromarray(rgb).save(OUT / "frame_rgb.png")
np.save(OUT / "frame_dn16.npy", out.dn16)
np.save(OUT / "frame_apparent_t_k.npy", out.apparent_t)

# Per object: median apparent temperature over its pixels away from every edge (the 7x7
# neighbourhood is all that object), against the prescribed surface temperature.
k = ctx["k"]
h, w = ctx["shape"]
ids = ids_ss[k // 2::k, k // 2::k][:h, :w]
paths = labels_to_paths(labels_from_payload(payload["instance"]))
rows = {}
im = Image.fromarray(gray).convert("RGB")
dr = ImageDraw.Draw(im)
r = 3
for ident, path in paths.items():
    name = path.rsplit("/", 1)[-1]
    if name not in thermal:
        continue
    m = ids == ident
    core = m.copy()
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            core &= np.roll(np.roll(m, dy, 0), dx, 1)
    if core.sum() == 0:
        continue
    t_app = float(np.median(out.apparent_t[core])) - 273.15
    mat, t_set = thermal[name]
    rows[name] = {"material": mat, "t_surface_c": t_set, "t_apparent_c_median": round(t_app, 2),
                  "pixels_core": int(core.sum()), "pixels": int(m.sum())}
    yy, xx = np.nonzero(core)
    y0, x0 = int(np.median(yy)), int(np.median(xx))
    if name.endswith("Cup"):
        y0 = max(2, int(yy.min()) - 52)
    dr.text((max(2, x0 - 40), max(2, y0)), f"{name}\nset {t_set:g} C\napp {t_app:.1f} C", fill=(255, 255, 0))
dr.text((6, h - 16), f"Cellplus CTC-007 sim | fixed window {lo:g}-{hi:g} C, white hot | air {P['room']['t_air_c']:g} C",
        fill=(255, 255, 0))
im.save(OUT / "frame_labelled.png")

f_px = ctx["spec"].optics.focal_length_mm * 1e3 / ctx["spec"].fpa.pitch_um
cups = {c["name"]: {"diameter_px_expected": round(2 * c["radius_m"] / math.hypot(c["distance_m"], pos[2] - c["height_m"] / 2) * f_px, 1)}
        for c in P["cups"]}
report = {"params": P, "params_file": str(PARAMS), "scene_yaml": str(scene_yaml), "camera_position": pos.tolist(),
          "camera_look": look.tolist(), "hfov_deg": ctx["hfov_deg"], "vfov_deg": ctx["vfov_deg"],
          "render_product_w_h": [ctx["shape_ss"][1], ctx["shape_ss"][0]], "objects": rows, "cups_geometry": cups,
          "field_of_view_at_cups_m": [round(2 * P["cups"][0]["distance_m"] * math.tan(math.radians(ctx[a] / 2)), 3)
                                      for a in ("hfov_deg", "vfov_deg")]}
(OUT / "report.json").write_text(json.dumps(report, indent=1, default=str))
for n_, r_ in rows.items():
    print(f"[two_cups] {n_:10s} {r_['material']:18s} set {r_['t_surface_c']:6.1f} C  apparent {r_['t_apparent_c_median']:6.2f} C  "
          f"({r_['pixels_core']} core px of {r_['pixels']})", flush=True)
print(f"wrote {OUT / 'report.json'}", flush=True)
ctx["app"].close()
